function getCurrentLang() {
  return localStorage.getItem('ryad_lang') || 'ar';
}

function t(key) {
  const lang = getCurrentLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
  return dict[key] || TRANSLATIONS.ar[key] || key;
}

function setLang(lang) {
  if (LANGUAGES[lang]) {
    localStorage.setItem('ryad_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = LANGUAGES[lang].dir;
    location.reload();
  }
}

function langSelectorHtml() {
  const cur = getCurrentLang();
  return `<select id="lang-select" onchange="setLang(this.value)" style="padding:4px 8px;border-radius:8px;border:1px solid #ccc;font-size:13px">
    ${Object.entries(LANGUAGES).map(([k,v]) => `<option value="${k}" ${k===cur?'selected':''}>${v.flag} ${v.name}</option>`).join('')}
  </select>`;
}

